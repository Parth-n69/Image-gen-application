/**
 * Autocorrect the last typed word in a text string relative to cursorPos.
 * @param {string} text
 * @param {number} cursorPos
 * @returns {{ newText: string, newCursorPos: number, original: string, corrected: string } | null}
 */
export function autocorrectLastWord(text, cursorPos) {
  let wordEnd = cursorPos;
  let wordStart = cursorPos;

  // Move back past trailing spaces/newlines
  while (wordEnd > 0 && /[\s]/.test(text[wordEnd - 1])) {
    wordEnd--;
  }

  // Find word start
  wordStart = wordEnd;
  while (wordStart > 0 && /[^\s]/.test(text[wordStart - 1])) {
    wordStart--;
  }

  if (wordStart === wordEnd) return null;

  const word = text.substring(wordStart, wordEnd);
  const lower = word.toLowerCase();

  const corrected = AUTOCORRECT_MAP[lower];
  if (!corrected || corrected === lower) return null;

  // Preserve original casing pattern
  let replacement;
  if (word === word.toUpperCase()) {
    replacement = corrected.toUpperCase();
  } else if (word[0] === word[0].toUpperCase()) {
    replacement = corrected.charAt(0).toUpperCase() + corrected.slice(1);
  } else {
    replacement = corrected;
  }

  const newText = text.substring(0, wordStart) + replacement + text.substring(wordEnd);
  const newCursorPos = cursorPos + (replacement.length - word.length);

  return {
    newText,
    newCursorPos,
    original: word,
    corrected: replacement,
  };
}
