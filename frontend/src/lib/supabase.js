import { createClient } from '@supabase/supabase-js';

const supabaseUrl = import.meta.env.VITE_SUPABASE_URL || '';
const supabaseAnonKey = import.meta.env.VITE_SUPABASE_ANON_KEY || '';

if (!supabaseUrl || !supabaseAnonKey) {
  console.warn(
    '[Supabase] Missing VITE_SUPABASE_URL or VITE_SUPABASE_ANON_KEY in frontend/.env.local.'
  );
}

export const supabase = createClient(supabaseUrl, supabaseAnonKey, {
  auth: {
    persistSession: true,
    autoRefreshToken: true,
    detectSessionInUrl: true,
  },
});

export const GUEST_MODE_ENABLED =
  import.meta.env.VITE_GUEST_MODE === 'true' ||
  import.meta.env.VITE_GUEST_MODE === undefined;

export const OTP_LENGTH = parseInt(import.meta.env.VITE_OTP_LENGTH || '8', 10);
